import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const ICONS_DIR = join(__dirname, "..", "icons");
const OUTPUT_FILE = join(__dirname, "..", "generated", "icons.ts");
const DATA_FILE = join(__dirname, "..", "generated", "icon-data.ts");

/**
 * Per-icon named exports get an `Icon` suffix (`home` -> `homeIcon`) so names
 * like `package` or `delete` never collide with reserved words.
 */
function toExportName(key: string): string {
  return `${key}Icon`;
}

const SVG_TAG_REGEX = /<svg\b[^>]*>([\s\S]*)<\/svg>/i;
const VIEW_BOX_REGEX = /viewBox\s*=\s*["']([^"']+)["']/i;

function toCamelCase(fileName: string): string {
  return fileName.replace(/-([a-z0-9])/gi, (_match, char: string) =>
    char.toUpperCase(),
  );
}

interface ParsedIcon {
  key: string;
  viewBox: string;
  path: string;
}

function parseSvgFile(fileName: string): ParsedIcon {
  const filePath = join(ICONS_DIR, fileName);
  const source = readFileSync(filePath, "utf-8");

  const svgMatch = SVG_TAG_REGEX.exec(source);
  if (!svgMatch) {
    throw new Error(`[build-icons] Could not find <svg>...</svg> in ${fileName}`);
  }

  const viewBoxMatch = VIEW_BOX_REGEX.exec(source);
  if (!viewBoxMatch) {
    throw new Error(`[build-icons] Could not find a viewBox attribute in ${fileName}`);
  }

  const key = toCamelCase(fileName.replace(/\.svg$/i, ""));
  const viewBox = viewBoxMatch[1];
  const path = svgMatch[1].trim().replace(/\s+/g, " ");

  return { key, viewBox, path };
}

const HEADER = "// This file is auto-generated by src/scripts/build-icons.ts. Do not edit by hand.";

/**
 * One named export per icon. Each is an independent, side-effect-free constant,
 * so bundlers keep only the icons an app actually imports.
 */
function buildIconDataSource(icons: ParsedIcon[]): string {
  const entries = icons
    .map(
      ({ key, viewBox, path }) =>
        `export const ${toExportName(key)}: IconDefinition = { viewBox: ${JSON.stringify(viewBox)}, path: ${JSON.stringify(path)} };`,
    )
    .join("\n");

  return `${HEADER}
import type { IconDefinition } from "../core/types.ts";

${entries}
`;
}

/** The by-name registry used by `getIcon(name)`; references the per-icon exports. */
function buildIconMapSource(icons: ParsedIcon[]): string {
  const entries = icons.map(({ key }) => `  ${key}: data.${toExportName(key)},`).join("\n");
  const nameUnion = icons.map(({ key }) => JSON.stringify(key)).join(" | ");

  return `${HEADER}
import type { IconDefinition } from "../core/types.ts";
import * as data from "./icon-data.ts";

// Declared explicitly (rather than derived via \`keyof typeof icons\`) because at this
// icon count TypeScript can't serialize the inferred type of \`icons\` into a .d.ts file.
export type IconName = ${nameUnion};

export const icons: Record<IconName, IconDefinition> = {
${entries}
};
`;
}

function main(): void {
  const svgFiles = readdirSync(ICONS_DIR).filter((file) =>
    file.toLowerCase().endsWith(".svg"),
  );

  if (svgFiles.length === 0) {
    throw new Error(`[build-icons] No .svg files found in ${ICONS_DIR}`);
  }

  const icons = svgFiles.map(parseSvgFile).sort((a, b) => a.key.localeCompare(b.key));

  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(DATA_FILE, buildIconDataSource(icons), "utf-8");
  writeFileSync(OUTPUT_FILE, buildIconMapSource(icons), "utf-8");

  console.log(`[build-icons] Processed ${icons.length} icon(s)`);
  console.log(`[build-icons] Wrote ${DATA_FILE}`);
  console.log(`[build-icons] Wrote ${OUTPUT_FILE}`);
}

main();
